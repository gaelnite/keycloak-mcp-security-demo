#!/usr/bin/env python3
"""Generate typed MCP wrappers from the public tool arguments in the registry."""

from __future__ import annotations

import argparse
from pathlib import Path

from tool_registry import TOOLS

OUTPUT = Path(__file__).with_name("generated_tool_wrappers.py")

HEADER = '''"""Generated by mcp/gen_tool_wrappers.py. Edit mcp/tool_registry.py."""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from typing import Any

from tool_registry import TOOLS_BY_NAME

AsyncTool = Callable[..., Awaitable[Any]]


def build_tool_functions(authorized_call: AsyncTool) -> dict[str, AsyncTool]:
    """Bind each MCP entry point to the same authorization and dispatch gate."""
'''


def render() -> str:
    wrappers = []
    entries = []
    for spec in TOOLS:
        parameters = []
        forwarded = []
        for arg in spec.arguments:
            parameter = f"{arg.name}: {arg.annotation.__name__}"
            if arg.default is not None:
                parameter += f" = {arg.default!r}"
            parameters.append(parameter)
            forwarded.append(f"{arg.name}={arg.name}")
        name = f"tool_{spec.name}"
        call = ", ".join([f'TOOLS_BY_NAME["{spec.name}"]', *forwarded])
        wrappers.append(
            f"    async def {name}({', '.join(parameters)}) -> Any:\n"
            f"        return await authorized_call({call})\n\n"
        )
        entries.append(f'        "{spec.name}": {name},\n')
    return HEADER + "".join(wrappers) + "    return {\n" + "".join(entries) + "    }\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.write_text(expected)
    elif not OUTPUT.is_file() or OUTPUT.read_text() != expected:
        parser.exit(1, "MCP tool wrappers are stale. Run python3 mcp/gen_tool_wrappers.py --write.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
